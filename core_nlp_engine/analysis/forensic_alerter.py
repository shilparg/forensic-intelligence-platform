import os
import json
import pandas as pd
import smtplib
from email.message import EmailMessage
import google.generativeai as genai
from dotenv import load_dotenv

# Try to import SendGrid (fail gracefully if not installed)
try:
    import sendgrid
    from sendgrid.helpers.mail import Mail, Email, To, Content
    SENDGRID_AVAILABLE = True
except ImportError:
    SENDGRID_AVAILABLE = False

# --- 1. Bulletproof Pathing & Environment ---
CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))         
ENGINE_DIR = os.path.abspath(os.path.join(CURRENT_DIR, ".."))    
PROJECT_ROOT = os.path.abspath(os.path.join(ENGINE_DIR, ".."))   

# Load environment variables
load_dotenv(os.path.join(PROJECT_ROOT, ".env"), override=True)

# Point to the CSV generated by Dagster's ML engine
DATA_PATH = os.path.join(ENGINE_DIR, "ml_engine", "ai_scored_forensic_dataset.csv")

def dispatch_genai_alert():
    print("🧠 Initializing Gen-AI Forensic Alerter...")
    
    # ==========================================================
    # --- TRUTH TABLE LEVEL 1: The .env Master Switch ---
    # ==========================================================
    env_alert_setting = os.getenv("EMAIL_ALERTS_ENABLED", "false").lower()
    if env_alert_setting == "false":
        print("🔕 ADMIN MUTE: Email alerts are strictly disabled in the .env file. Skipping dispatch.")
        return

    # ==========================================================
    # --- TRUTH TABLE LEVEL 2: The Streamlit UI Toggle ---
    # ==========================================================
    ui_state_path = os.path.join(PROJECT_ROOT, "ui_state.json")
    if os.path.exists(ui_state_path):
        try:
            with open(ui_state_path, "r") as f:
                ui_data = json.load(f)
                alerts_enabled = ui_data.get("enable_alerts", False)
                if not alerts_enabled:
                    print("🔕 USER MUTE: Email alerts disabled via Streamlit UI. Skipping dispatch.")
                    return
        except Exception as e:
            print(f"⚠️ Warning: Could not read UI state. Error: {e}")

    # --- 2. System Authentication ---
    GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
    if not GEMINI_API_KEY:
        print("🚨 Error: GEMINI_API_KEY not found in .env.")
        return

    genai.configure(api_key=GEMINI_API_KEY)
    model = genai.GenerativeModel('gemini-1.5-flash')

    # --- 3. Load the Forensic Data ---
    if not os.path.exists(DATA_PATH):
        print(f"🚨 Error: ML output not found at {DATA_PATH}.")
        return

    df = pd.read_csv(DATA_PATH)
    
    # Match the exact label outputted by our Isolation Forest model
    critical_targets = df[df['fraud_risk_status'] == 'CRITICAL ANOMALY']

    if critical_targets.empty:
        print("✅ No critical anomalies detected today. No alerts to send.")
        return

    print(f"⚠️ Found {len(critical_targets)} Critical Anomalies. Drafting Executive Memos...")

    # --- 4. Generate AI Memos for ALL Anomalies ---
    full_email_body = f"🚨 AUTOMATED FORENSIC PLATFORM ALERT 🚨\n\n"
    full_email_body += f"The Isolation Forest engine has flagged {len(critical_targets)} targets requiring immediate auditor review.\n"
    full_email_body += "="*60 + "\n\n"

    for _, target in critical_targets.iterrows():
        ticker = target['ticker']
        sentiment = target.get('sentiment_score', 0.0)
        short_ratio = target.get('short_ratio', 0.0)
        debt_to_equity = target.get('debt_to_equity', 0.0)

        prompt = f"""
        You are a Senior Forensic Audit Partner at a Big Four accounting firm. 
        You are receiving an automated alert regarding a critical anomaly detected in a client's recent SEC 10-K filing.

        Review the following risk triangulation metrics for {ticker}:
        - Management Discussion & Analysis (MD&A) Sentiment Score: {sentiment} (Scale: -1.0 to 1.0, below 0.1 is highly defensive)
        - Open Market Short Ratio: {short_ratio} (Values above 4.0 indicate severe market pessimism)
        - Debt-to-Equity Ratio: {debt_to_equity}% (Values above 150% indicate high leverage risk)

        Task: Write a highly concise, 3-bullet-point executive summary to the Audit Engagement Team. 

        Strict Guidelines:
        1. Tone: Clinical, objective, and highly professional. Use standard audit terminology (e.g., "going concern risk", "narrative obfuscation").
        2. Format: Output ONLY the three bullet points. Do not include greetings.
        3. Analysis: Briefly synthesize *why* the combination of these specific metrics suggests management might be hiding financial distress in the narrative.
        """

        try:
            response = model.generate_content(prompt)
            full_email_body += f"🎯 TARGET: {ticker}\n"
            
            # Safe formatting just in case missing data was imputed as a string
            try:
                full_email_body += f"Metrics -> Sent: {float(sentiment):.2f} | Short: {float(short_ratio):.1f} | D/E: {float(debt_to_equity):.1f}\n\n"
            except ValueError:
                full_email_body += f"Metrics -> Sent: {sentiment} | Short: {short_ratio} | D/E: {debt_to_equity}\n\n"
                
            full_email_body += "🤖 AI Partner Synthesis:\n"
            full_email_body += f"{response.text.strip()}\n\n"
            full_email_body += "-"*60 + "\n\n"
        except Exception as e:
            print(f"🚨 Failed to generate Gemini summary for {ticker}: {e}")
            full_email_body += f"🎯 TARGET: {ticker}\n[AI Generation Failed - Manual Review Required]\n\n"

    # --- 5. Dispatch the Email ---
    provider = os.getenv("EMAIL_PROVIDER", "gmail").lower()
    recipient_raw = os.getenv("AUDIT_EMAIL_RECIPIENT", "")
    recipients = [email.strip() for email in recipient_raw.split(",") if email.strip()]

    if not recipients:
        print("❌ Email recipients missing in .env. Printing to console instead:")
        print(full_email_body)
        return

    subject = f"🚨 AI AUDIT ALERT: {len(critical_targets)} Critical Anomalies Detected"

    if provider == "sendgrid":
        print("🚀 Dispatching via SendGrid API...")
        if not SENDGRID_AVAILABLE:
            print("❌ Error: SendGrid package not installed. Run 'pip install sendgrid'")
            return
            
        try:
            from_email = os.getenv("SENDGRID_FROM_EMAIL")
            sg_key = os.getenv("SENDGRID_API_KEY")

            if not from_email or not sg_key:
                print("❌ SendGrid credentials missing in .env. Aborting.")
                return

            sg = sendgrid.SendGridAPIClient(api_key=sg_key)
            from_obj = sendgrid.helpers.mail.Email(from_email, os.getenv('SMTP_NAME', 'AI Auditor'))
            to_emails = [sendgrid.helpers.mail.To(email) for email in recipients]
            content = sendgrid.helpers.mail.Content("text/plain", full_email_body)
            message = sendgrid.helpers.mail.Mail(from_obj, to_emails, subject, content)
            
            response = sg.client.mail.send.post(request_body=message.get())
            print(f"✅ Alert successfully dispatched via SendGrid to the Audit Team! (Status: {response.status_code})")
            
        except Exception as e:
            print(f"❌ Failed to send via SendGrid: {e}")

    else:
        print("⏳ Dispatching via Gmail SMTP...")
        user = os.getenv("GMAIL_USER")
        pwd = os.getenv("GMAIL_APP_PASSWORD")

        if not user or not pwd:
            print("❌ Gmail credentials missing in .env. Aborting.")
            return

        msg = EmailMessage()
        msg.set_content(full_email_body)
        msg['Subject'] = subject
        msg['From'] = f"{os.getenv('SMTP_NAME', 'Forensic Bot')} <{user}>"
        msg['To'] = ", ".join(recipients)

        try:
            server = smtplib.SMTP("smtp.gmail.com", 587, timeout=15)
            server.starttls()
            server.login(user, pwd)
            server.send_message(msg, to_addrs=recipients)
            server.quit()
            print("✅ Alert successfully dispatched via Gmail to the Audit Team!")
        except Exception as e:
            print(f"❌ Failed to send via Gmail: {e}")

if __name__ == "__main__":
    dispatch_genai_alert()